            en: enStrings[entry.key] ?? entry.value,
            locale: locale,
          ),
        ),
    ];
    final dynamicEntries = <MapEntry<String, String>>[
      for (final key in azDynamicStrings.keys)
        MapEntry(
          key,
          _translate(
            vi: key,
            en: _dynamicEnglish[key] ?? enStrings[key] ?? key,
            locale: locale,
          ),
        ),
    ];

    _writeMapFile(
      path: 'lib/localization/languages/${locale.code}_strings.dart',
      mapName: locale.baseName,
      entries: baseEntries,
    );
    _writeMapFile(
      path: 'lib/localization/languages/${locale.code}_dynamic_strings.dart',
      mapName: locale.dynamicName,
      entries: dynamicEntries,
    );
  }
}

String _translate({
  required String vi,
  required String en,
  required LocaleSpec locale,
}) {
  final exact = locale.exact[vi] ?? locale.exact[en];
  if (exact != null) {
    return exact;
  }

  final protectedValues = <String>[];
  var text = en.replaceAllMapped(_protectedPattern, (match) {
    protectedValues.add(match.group(0)!);
    return '§${protectedValues.length - 1}§';
  });

  final entries = locale.dictionary.entries.toList()
    ..sort((a, b) => b.key.length.compareTo(a.key.length));

  for (final entry in entries) {
    if (_shouldSkipDictionaryEntry(entry)) {
      continue;
    }

    text = text.replaceAllMapped(_dictionaryPattern(entry.key), (match) {
      return '${match.group(1) ?? ''}${entry.value}';
    });
  }

  for (var index = 0; index < protectedValues.length; index++) {
    text = text.replaceAll('§$index§', protectedValues[index]);
  }

  text = text
      .replaceAll(RegExp(r'[ \t]{2,}'), ' ')
      .replaceAll(RegExp(r' *\\n *'), r'\n')
      .trim();

  return text.isEmpty ? locale.dictionary['SafeHome'] ?? 'SafeHome' : text;
}

void _writeMapFile({
  required String path,
  required String mapName,
  required List<MapEntry<String, String>> entries,
}) {
  final buffer = StringBuffer()
    ..writeln('const Map<String, String> $mapName = {');

  for (final entry in entries) {
    buffer.writeln(
      '  "${_dartString(entry.key)}": "${_dartString(entry.value)}",',
    );
  }

  buffer.writeln('};');
  File(path).writeAsStringSync(buffer.toString());
}

String _dartString(String value) {
  return value
      .replaceAll('\\', r'\\')
      .replaceAll(r'$', r'\$')
      .replaceAll('"', r'\"')
      .replaceAll('\r', '')
      .replaceAll('\n', r'\n');
}

final _protectedPattern = RegExp(
  r'\$\{?[A-Za-z_][A-Za-z0-9_]*\}?|SafeHome|HomeChat|SOS|CO₂|CO2|\bCO\b|PM2\.5|Wi-Fi|Zigbee|MQTT|GPS|Android|iOS|Face ID|Touch ID|Firebase|FCM|QR|UID|UPS|AI|OK',
);

RegExp _dictionaryPattern(String source) {
  const letterClass = r'A-Za-zÀ-ÖØ-öø-ÿĀ-ỹ';
  final escaped = RegExp.escape(source.trim());

  return RegExp(
    '(^|[^$letterClass])$escaped(?=\$|[^$letterClass])',
    caseSensitive: false,
    unicode: true,
  );
}

bool _shouldSkipDictionaryEntry(MapEntry<String, String> entry) {
  final key = entry.key.trim().toLowerCase();

  return entry.value.isEmpty && key == 'a';
}

